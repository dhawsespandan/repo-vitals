"""`research_data/validation_report/` — study S1's results section, generated.

§10 Phase 12: "`report.py` -> `research_data/validation_report/` (report.md +
correlation scatter, weight-comparison chart, sensitivity table, confusion
matrices as PNG/CSV)." The mentor demo reads it aloud: "This folder is study
S1's results section, generated by one command."

**It opens with WP-6's sign-off checklist, already computed.** File B gives the
teammate six checks to walk in `wp6_signoff.md`; each is a line here with its
number filled in and a verdict beside it, in the same spirit as the corpus
reports (§11.15). A run that fails one fails it on the first page.

**Every caveat sits beside the number it qualifies.** File C §2.4.3: the OSV
reference's circularity sentence goes "adjacent to the number, not buried".
The Scorecard construct caveat, the sampling-weight note and the
cross-sectional limit are placed the same way.

**Figures are optional; the CSVs are not.** The PNGs need matplotlib, which is
research-only and was blocked by an Application Control policy on the
development machine (§11.22). Every figure's data is also a CSV, so a machine
that cannot draw still produces every number, and the report says which
figures were skipped and why.

**The candidate weights file is written here and nowhere else.** It is named
`weights_v2_candidate.yaml`, carries `derivation: ahp-candidate-pending-wp6`,
and is validated by the product's own loader before it is written. It is not
in `backend/weights/` and nothing loads it: adopting it is §10 Phase 12's
seventh commit, after WP-6 signs.
"""

