_PARAMETERS = re.compile(r"bootstrap over items, (\d+) resamples, seed (\d+)")


def analysis_parameters(directory: Path) -> tuple[int, int]:
    """The bootstrap size and seed the signed S3 tables state in their header."""
    text = (directory / ANALYSIS_DIR / "tables.md").read_text(encoding="utf-8")
    found = _PARAMETERS.search(text)
    if found is None:
        raise ReplicationError("The signed tables.md does not state its bootstrap.")
    return int(found.group(1)), int(found.group(2))


