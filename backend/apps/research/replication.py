"""The analysis notebooks' side of the replication package (§10 Phase 14).

`notebooks/13_3_validation.ipynb` (S1) and `notebooks/13_1_analysis.ipynb`
(S3) are thin: every computation they show is a function here, and every
function here is either the harness's own code fed from an export folder or a
comparison with what the harness wrote when the study's data was signed. That
is what "exports regenerate every notebook table" means in practice — the
tables are regenerated by the code that made them, from the files a stranger
has, and then checked against the signed copies.

**Nothing here opens a database.** The notebooks run under
`config.settings.offline`, whose database backend raises on the first query,
and these loaders read Parquet and JSON. The one network call either harness
could make (deps.dev for S1, the judge for S3) is replaced by its recorded
answers: WP-6's `depsdev_cache.jsonl` and WP-8's per-item verdicts in
`runs/analysis/metrics.csv`. A missing recorded answer fails rather than
fetching.

**What is recomputed and what is read.** S1: everything, from the stored
signals — scores, entropy weights, agreement, sensitivity, anchors — with
deps.dev's Scorecards read as observed on the day. S3: correctness, which is a
program, from the generations and the labelled set; faithfulness and
precision@k are the judge's verdicts as WP-8 recorded them (the judge cache is
withheld, decisions §13.17, and a judge call is not reproducible anyway).
"""

