# ── S3: the runs and their tables ──────────────────────────────────────────


def run_directories(directory: Path) -> list[Path]:
    """Every run folder in the export, in condition order (A, B, C, D)."""
    found = []
    for path in sorted((directory / RUNS_DIR).iterdir()):
        manifest = path / runner.RUN_FILENAME
        if manifest.exists():
            condition = json.loads(manifest.read_text(encoding="utf-8"))["condition"]
            found.append((condition, path))
    return [path for _, path in sorted(found)]


def recorded_verdicts(directory: Path) -> dict[tuple[str, str], dict]:
    """The judge's verdicts per (item, condition), as WP-8's analysis wrote them."""
    path = directory / ANALYSIS_DIR / "metrics.csv"
    with path.open(encoding="utf-8", newline="") as handle:
        return {(row["item_id"], row["condition"]): row for row in csv.DictReader(handle)}


def _judgments(row: dict | None) -> dict:
    if row is None:
        return {}
    found: dict = {}
    if row["faithfulness"]:
        found[judge.FAITHFULNESS] = {
            "verdict": row["faithfulness"],
            "stated_verdict": row["stated_verdict"] or None,
        }
    if row["precision_at_k"]:
        found[judge.RELEVANCE] = {
            "precision_at_k": float(row["precision_at_k"]),
            "k": int(row["k"]),
        }
    return found


#: The columns of `metrics.csv` that are computed by program from the runs and
#: the labelled set — the ones a replication recomputes rather than reads.
DETERMINISTIC = (
    "ecosystem",
    "case_type",
    "answer_given",
    "status",
    "grounding",
    "branch",
    "correct",
    "correctness_reason",
    "declared_insufficient",
)


@dataclass
class S3Replication:
    dataset: analysis.Dataset
    #: (item, condition, column, recorded, recomputed) for every disagreement.
    disagreements: list[tuple[str, str, str, str, str]]


def _as_csv(value) -> str:
    return "" if value is None else str(value)


def s3_dataset(directory: Path) -> S3Replication:
    """WP-8's analysis dataset, with correctness recomputed from the generations."""
    items, _ = runner.load_items(directory / LABELLED_SET)
    by_id = {item["item_id"]: item for item in items}
    verdicts = recorded_verdicts(directory)
    run_dirs = run_directories(directory)
    if not run_dirs:
        raise ReplicationError(f"No run folders under {directory / RUNS_DIR}.")

    manifests = {}
    rows: list[metrics.ItemMetrics] = []
    disagreements = []
    unjudged = 0
    for run_dir in run_dirs:
        manifest = json.loads((run_dir / runner.RUN_FILENAME).read_text(encoding="utf-8"))
        manifests[manifest["condition"]] = manifest
        for record in runner.latest_records(run_dir / runner.ITEMS_FILENAME).values():
            item = by_id.get(record["item_id"])
            if item is None:
                raise ReplicationError(
                    f"{record['item_id']} is in {run_dir.name} but not in the labelled set."
                )
            recorded = verdicts.get((record["item_id"], record["condition"]))
            row = metrics.measure(record, item, _judgments(recorded))
            if row.status == "ok" and row.faithfulness is None:
                unjudged += 1
            rows.append(row)
            if recorded is None:
                disagreements.append(
                    (row.item_id, row.condition, "*", "", "not recorded")
                )
                continue
            for column in DETERMINISTIC:
                ours = _as_csv(getattr(row, column))
                if ours != recorded[column]:
                    disagreements.append(
                        (row.item_id, row.condition, column, recorded[column], ours)
                    )
    dataset = analysis.Dataset(runs=manifests, rows=rows, unjudged=unjudged)
    return S3Replication(dataset=dataset, disagreements=disagreements)


WP9_PACKET = "judge_validation/judge_validation_packet.md"
WP9_LABELS = "judge_validation/wp9_judge_labels.csv"


def wp9_candidates(directory: Path) -> list[judge_validation.Candidate]:
    """Every judged generation in the export, as the packet sampler saw them.

    The judge's verdict is the recorded one (`metrics.csv`); the passages are
    the ones the generation was shown, exactly as `judged_candidates` picks
    them, because the packet rendered those.
    """
    items, _ = runner.load_items(directory / LABELLED_SET)
    by_id = {item["item_id"]: item for item in items}
    verdicts = recorded_verdicts(directory)
    found: list[judge_validation.Candidate] = []
    for run_dir in run_directories(directory):
        for record in runner.latest_records(run_dir / runner.ITEMS_FILENAME).values():
            item = by_id.get(record["item_id"])
            recorded = verdicts.get((record["item_id"], record["condition"])) or {}
            if record.get("status") != "ok" or item is None:
                continue
            if not recorded.get("faithfulness"):
                continue
            shown_ids = set(record.get("shown_chunk_ids") or [])
            shown = [
                chunk
                for chunk in record.get("retrieved") or []
                if str(chunk.get("chunk_id")) in shown_ids
            ]
            found.append(
                judge_validation.Candidate(
                    run_dir.name,
                    record,
                    item,
                    {"verdict": recorded["faithfulness"], "shown": shown},
                )
            )
    return found


def wp9_key(directory: Path, *, seed: int = 42) -> dict[str, dict]:
    """WP-9's answer key, rebuilt from the export and checked against its packet.

    The sample size is the packet's own item count; the seed is the one every
    WP-9 packet was drawn with (REPLICATION.md §6).
    """
    packet = (directory / WP9_PACKET).read_text(encoding="utf-8")
    size = len(re.findall(r"^## ITEM-\d{3}$", packet, flags=re.MULTILINE))
    if not size:
        raise judge_validation.ValidationPacketError(
            f"{WP9_PACKET} holds no packet items."
        )
    return judge_validation.reconstruct_key(
        wp9_candidates(directory), packet, size=size, seed=seed
    )


