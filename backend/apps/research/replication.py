def manifest_summary(manifest: dict) -> str:
    """The export's receipt as a markdown table."""
    git = manifest.get("git") or {}
    commit = git.get("commit") or "unknown"
    dirty = " (local changes)" if git.get("dirty") else ""
    lines = [
        "| | |",
        "|---|---|",
        f"| Exported | {manifest['generated_at'][:19]}Z |",
        f"| At commit | `{commit[:12]}`{dirty} |",
        f"| Database | {manifest['database']['vendor']} `{manifest['database']['name']}` |",
        f"| Sources | {', '.join(manifest['sources'])} |",
    ]
    for name, table in manifest["tables"].items():
        detail = ", ".join(
            f"{key} {value}"
            for key, value in (table.get("by_snapshot_date") or {}).items()
        )
        lines.append(
            f"| `{name}` | {table['rows']} rows{f' ({detail})' if detail else ''} |"
        )
    lines.append(f"| Files | {len(manifest['files'])}, each with its sha256 |")
    return "\n".join(lines)


def comparison_table(results: list[FileComparison]) -> str:
    lines = ["| File | Against the signed copy |", "|---|---|"]
    for result in results:
        note = f" ({result.float_cells} cells)" if result.float_cells else ""
        lines.append(f"| `{result.name}` | **{result.status}**{note} |")
    return "\n".join(lines)


def classification_table(corpus: panel.CorpusPanel, versions: list[str]) -> str:
    """Safe / Medium / High alert per weights file, each recomputed (D6)."""
    from apps.scoring.weights import load_weights

    lines = [
        "| Weights | Derivation | Safe | Medium | High alert | Median score |",
        "|---|---|---|---|---|---|",
    ]
    for version in versions:
        weights = load_weights(version)
        scores = panel.score_panel(corpus, weights)
        counts = dict.fromkeys(("safe", "medium", "high_alert"), 0)
        for score in scores:
            counts[score.classification] += 1
        ordered = sorted(score.score for score in scores)
        middle = len(ordered) // 2
        median = (
            ordered[middle]
            if len(ordered) % 2
            else (ordered[middle - 1] + ordered[middle]) / 2
        )
        lines.append(
            f"| `{version}` | {weights.derivation} | {counts['safe']} | "
            f"{counts['medium']} | {counts['high_alert']} | {median:.2f} |"
        )
    return "\n".join(lines)


def reweighted(weights, multipliers: dict[str, float], *, version: str):
    """`weights` with signals multiplied and renormalized — a reviewer's "what if".

    File C §1.1: "a reviewer request like 'what if staleness were weighted
    double?' is a notebook cell, not a data-collection round."
    """
    from apps.research.validation import candidates

    vectors = {
        ecosystem: {
            signal: float(weight) * multipliers.get(signal, 1.0)
            for signal, weight in vector.items()
        }
        for ecosystem, vector in weights.weights.items()
    }
    return candidates.weightset_from(
        weights, vectors, version=version, derivation="notebook-reweighting"
    )


def flip_table(corpus: panel.CorpusPanel, before, after) -> str:
    """How many repositories change class between two weightings."""
    first = panel.score_panel(corpus, before)
    second = panel.score_panel(corpus, after)
    moves: dict[tuple[str, str], int] = {}
    for one, two in zip(first, second, strict=True):
        key = (one.classification, two.classification)
        moves[key] = moves.get(key, 0) + 1
    flipped = sum(count for (a, b), count in moves.items() if a != b)
    lines = [
        f"{flipped} of {len(first)} repositories change class "
        f"({flipped / len(first):.1%}) from `{before.version}` to `{after.version}`.",
        "",
        f"| `{before.version}` | `{after.version}` | Repositories |",
        "|---|---|---|",
    ]
    for (a, b), count in sorted(moves.items()):
        lines.append(f"| {a} | {b} | {count} |")
    return "\n".join(lines)
